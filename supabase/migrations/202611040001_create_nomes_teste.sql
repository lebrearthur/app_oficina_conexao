create table if not exists public.nomes_teste (
  id bigint generated by default as identity primary key,
  nome text not null check (char_length(trim(nome)) between 1 and 120),
  created_at timestamptz not null default now()
);
alter table public.nomes_teste enable row level security;
grant insert on table public.nomes_teste to anon, authenticated;
grant usage, select on sequence public.nomes_teste_id_seq to anon, authenticated;
create policy "Permitir cadastro de nomes para teste"
on public.nomes_teste for insert to anon, authenticated
with check (char_length(trim(nome)) between 1 and 120);
